def set_para_text(p, text):
    """整段替换文本。参考 rPr 优先取带 eastAsia 字体定义的 run，避免继承无字体的序号标记 run。"""
    ref, ref_fallback = None, None
    for r in p.runs:
        rPr_el = r._element.find(qn('w:rPr'))
        if rPr_el is None:
            continue
        if ref_fallback is None:
            ref_fallback = rPr_el
        rf = rPr_el.find(qn('w:rFonts'))
        if rf is not None and rf.get(qn('w:eastAsia')):
            ref = rPr_el
            break
    ref = ref or ref_fallback
    # 删除全部 run
    for r in list(p.runs):
        r._element.getparent().remove(r._element)
    run = p.add_run(text)
    r_el = run._element
    old = r_el.find(qn('w:rPr'))
    new_rPr = copy.deepcopy(ref) if ref is not None else (old if old is not None else None)
    if old is not None:
        r_el.remove(old)
    if new_rPr is None:
        from docx.oxml import OxmlElement
        new_rPr = OxmlElement('w:rPr')
    # 确保 eastAsia 字体为仿宋_GB2312（模板正文字体），规避无字体 run
    rf = new_rPr.find(qn('w:rFonts'))
    if rf is None:
        from docx.oxml import OxmlElement
        rf = OxmlElement('w:rFonts')
        new_rPr.insert(0, rf)
    rf.set(qn('w:eastAsia'), '仿宋_GB2312')
    rf.set(qn('w:ascii'), '仿宋_GB2312')
    rf.set(qn('w:hAnsi'), '仿宋_GB2312')
    r_el.insert(0, new_rPr)
    return p

